<#
.SYNOPSIS
    Writes the SQL scripts that create SivaComm's tables, for a DBA who wants
    to read or run the SQL rather than let the installer do it.

.DESCRIPTION
    Two files, both generated — never edit them by hand:

      migrate.sql       EF Core's own idempotent migration script: every
                        migration, each wrapped so it only runs if it has not
                        been applied. Run against an existing database, as the
                        application role.

      full-schema.sql   deploy\sql\01-create-database.sql (role, database,
                        schema, privileges) followed by migrate.sql run as the
                        application role: one psql command takes a blank
                        server to a ready database.

    Both are safe to re-run, and safe alongside the installer's
    `SivaComm.Api.exe --migrate`: each skips what the other already applied.

    Re-run after every `dotnet ef migrations add`. New-Release.ps1 runs it for
    every release, so the zip always matches its own migrations.

.PARAMETER OutDir
    Where to write. Default: db\ in the repository.

.EXAMPLE
    .\deploy\New-SchemaScripts.ps1
#>

[CmdletBinding()]
param([string] $OutDir)

$ErrorActionPreference = 'Stop'
$Repo = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$DataProj = Join-Path $Repo 'backend\src\SivaComm.Data'
$Setup = Join-Path $PSScriptRoot 'sql\01-create-database.sql'
if (-not $OutDir) { $OutDir = Join-Path $Repo 'db' }
New-Item -ItemType Directory -Force $OutDir | Out-Null

$Migrate = Join-Path $OutDir 'migrate.sql'
$Full = Join-Path $OutDir 'full-schema.sql'
$utf8 = New-Object System.Text.UTF8Encoding($false)

$env:MSBUILDDISABLENODEREUSE = '1'
& dotnet ef migrations script --idempotent --project $DataProj --startup-project $DataProj -o $Migrate | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'dotnet ef migrations script failed (is dotnet-ef installed? dotnet tool install -g dotnet-ef).' }

# Strip the BOM dotnet ef writes: psql would glue it onto the first statement.
$schema = [IO.File]::ReadAllText($Migrate).TrimStart([char]0xFEFF)

$migrateHeader = @'
-- ============================================================================
--  SivaComm - schema migrations, idempotent. GENERATED by
--  deploy\New-SchemaScripts.ps1 from backend\src\SivaComm.Data\Migrations -
--  do not edit by hand.
--
--  Creates or upgrades every table in schema comm. Each migration runs only if
--  public."__EFMigrationsHistory" says it has not been applied, so this is
--  safe to run again, and safe alongside SivaComm.Api.exe --migrate (which
--  reads and writes the same history table).
--
--  Run against an existing database (01-create-database.sql makes one), as
--  the application role, so the tables are owned by it:
--
--      psql -h localhost -U sivacomm -d sivacomm -f migrate.sql
-- ============================================================================

\set ON_ERROR_STOP on


'@
[IO.File]::WriteAllText($Migrate, $migrateHeader + $schema, $utf8)

$setupText = [IO.File]::ReadAllText($Setup)
$cut = $setupText.IndexOf('-- END-OF-SETUP')
if ($cut -lt 0) { throw "$Setup has lost its END-OF-SETUP marker." }

$fullHeader = @'
-- ============================================================================
--  SivaComm - complete database script for PostgreSQL 16+. GENERATED by
--  deploy\New-SchemaScripts.ps1 - do not edit by hand.
--
--  Takes a blank server to a ready database in one run, as the superuser:
--
--      psql -U postgres -v app_password='<choose one>' -f full-schema.sql
--
--  1. role, database, schema comm, privileges  (= 01-create-database.sql)
--  2. SET ROLE to the application role, then every table, index and
--     constraint, and the __EFMigrationsHistory rows  (= migrate.sql)
--
--  Safe to re-run. No data is inserted: applications, keys and templates come
--  from the Applications section of appsettings.Production.json when the
--  service starts, and the first dashboard admin from its Admin section.
-- ============================================================================

'@

$roleSwitch = @'

-- ----------------------------------------- tables, as the application role

-- Owned by the application role, not postgres: its later migrations must be
-- able to alter them.
SET ROLE :"app_user";

'@

$footer = @'

RESET ROLE;
\echo
\echo Applied migrations:
SELECT migration_id FROM public."__EFMigrationsHistory" ORDER BY 1;
\echo Tables in schema comm, and who owns them:
SELECT count(*) AS tables, tableowner FROM pg_tables WHERE schemaname = 'comm' GROUP BY tableowner;
\echo Done. Set Database:Password in appsettings.Production.json and run Install-SivaComm.ps1.
'@

[IO.File]::WriteAllText($Full, $fullHeader + $setupText.Substring(0, $cut) + $roleSwitch + $schema + $footer, $utf8)

Write-Host "Wrote $Migrate ($([math]::Round((Get-Item $Migrate).Length / 1KB)) KB)"
Write-Host "Wrote $Full ($([math]::Round((Get-Item $Full).Length / 1KB)) KB)"
